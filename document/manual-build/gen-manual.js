// ---------- 基础助手 ----------
function txt(text, o = {}) {
  return new TextRun({ text, font: FONT, size: o.size || 21, bold: !!o.bold,
    italics: !!o.italics, color: o.color || INK, break: o.break || 0 });
}

function para(text, o = {}) {
  children.push(new Paragraph({
    spacing: { before: o.before ?? 60, after: o.after ?? 60, line: 300 },
    alignment: o.align,
    indent: o.indent,
    children: Array.isArray(text) ? text : [txt(text, o)],
  }));
}

let listSeq = 0;    // 编号列表序列：每个 h1 / 每个操作流程各占一个 numbering 引用
let stepRef = "L0"; // 当前列表引用，保证每个流程的步骤号从 1 开始
function nextList() { listSeq += 1; stepRef = "L" + listSeq; }
function h1(text) {
  nextList();
  children.push(new Paragraph({ heading: HeadingLevel.HEADING_1,
    spacing: { before: 360, after: 160 }, pageBreakBefore: true,
    children: [new TextRun({ text, font: FONT, size: 32, bold: true, color: DEEP })] }));
}
function h2(text) {
  children.push(new Paragraph({ heading: HeadingLevel.HEADING_2,
    spacing: { before: 280, after: 120 },
    children: [new TextRun({ text, font: FONT, size: 26, bold: true, color: INK })] }));
}
function h3(text) {
  children.push(new Paragraph({ heading: HeadingLevel.HEADING_3,
    spacing: { before: 200, after: 100 },
    children: [new TextRun({ text, font: FONT, size: 22, bold: true, color: INK2 })] }));
}

function bullet(text, level = 0) {
  children.push(new Paragraph({
    numbering: { reference: "bullets", level },
    spacing: { before: 40, after: 40, line: 300 },
    children: Array.isArray(text) ? text : [txt(text)],
  }));
}
// 开始新的操作流程：其后 numbered() 从 1 重新编号
function newList() { nextList(); }
function numbered(text, ref, level = 0) {
  children.push(new Paragraph({
    numbering: { reference: ref || stepRef, level },
    spacing: { before: 40, after: 40, line: 300 },
    children: Array.isArray(text) ? text : [txt(text)],
  }));
}

// 提示框（注意/说明）：浅色底 + 左侧色条，用单元格表格实现
// opts.noGap: 不追加表格后的空段落（章末使用，避免空段落溢到下一页形成空白页）
function noteBox(title, lines, color = ACC, bg = WASH, opts = {}) {
  const left = new TableCell({ width: { size: 80, type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, fill: color },
    borders: noBorders(),
    children: [new Paragraph({ children: [txt("", {})] })] });
  const right = new TableCell({ width: { size: 9000, type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, fill: bg },
    borders: noBorders(),
    margins: { top: 120, bottom: 120, left: 200, right: 160 },
    children: [
      new Paragraph({ spacing: { after: 60 },
        children: [txt(title, { bold: true, color })] }),
      ...lines.map(l => new Paragraph({ spacing: { before: 20, after: 20, line: 280 },
        children: Array.isArray(l) ? l : [txt(l, { size: 20 })] })),
    ] });
  children.push(new Table({ width: { size: 9080, type: WidthType.DXA },
    columnWidths: [80, 9000], rows: [new TableRow({ children: [left, right] })] }));
  if (!opts.noGap) para("", { before: 0, after: 40 });
}

function noBorders() {
  const n = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  return { top: n, bottom: n, left: n, right: n, insideHorizontal: n, insideVertical: n };
}
function thinBorders(color = GRID) {
  const b = { style: BorderStyle.SINGLE, size: 4, color };
  return { top: b, bottom: b, left: b, right: b, insideHorizontal: b, insideVertical: b };
}

// 通用表格：headers[], rows[][], widths[]（DXA，合计约 9080）
function table(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const headRow = new TableRow({ tableHeader: true,
    children: headers.map((h, i) => new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      shading: { type: ShadingType.CLEAR, fill: DARK },
      borders: thinBorders(), margins: cellMargins(),
      children: [new Paragraph({ children: [txt(h, { bold: true, color: "FFFFFF", size: 20 })] })],
    })) });
  const bodyRows = rows.map((r, ri) => new TableRow({
    children: r.map((c, i) => new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      shading: ri % 2 ? { type: ShadingType.CLEAR, fill: "F7F7F5" } : undefined,
      borders: thinBorders(), margins: cellMargins(),
      children: [new Paragraph({ spacing: { line: 270 },
        children: Array.isArray(c) ? c : [txt(String(c), { size: 20 })] })],
    })),
  }));
  children.push(new Table({ width: { size: total, type: WidthType.DXA },
    columnWidths: widths, rows: [headRow, ...bodyRows] }));
  para("", { before: 0, after: 60 });
}
function cellMargins() { return { top: 70, bottom: 70, left: 110, right: 110 }; }

// 截图：存在则嵌入（带细边框），否则占位说明
function shot(role, name, w, caption) {
  const f = path.join(SHOT, role, name + ".png");
  if (fs.existsSync(f)) {
    children.push(new Paragraph({ alignment: AlignmentType.CENTER,
      spacing: { before: 120, after: 40 },
      children: [new ImageRun({ type: "png", data: fs.readFileSync(f),
        transformation: { width: w, height: Math.round(w * 9 / 16) },
        altText: { title: caption || name, description: caption || name, name } })] }));
  } else {
    noteBox("（截图占位）", [`系统界面截图 ${role}/${name} 生成后自动替换`], MUT, "F7F7F5");
  }
  if (caption) {
    children.push(new Paragraph({ alignment: AlignmentType.CENTER,
      spacing: { after: 160 },
      children: [txt(caption, { size: 18, italics: true, color: MUT })] }));
  }
}

